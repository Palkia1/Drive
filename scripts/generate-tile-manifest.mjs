// Scans public/tiles/ and writes src/lib/questions/realTiles.generated.ts —
// a map of TileKind -> file extension, so GridScene knows which tiles have
// real artwork vs. need the flat placeholder fallback. Re-run this after
// adding or removing files in public/tiles/ (npm run tiles:manifest).
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const tilesDir = path.join(root, "..", "public", "tiles");
const outFile = path.join(root, "..", "src", "lib", "questions", "realTiles.generated.ts");

const KNOWN_KINDS = [
  "grass",
  "straight",
  "corner",
  "t-junction",
  "crossroad",
  "roundabout-center",
  "narrow-residential",
  "wide-curve",
];

const entries = readdirSync(tilesDir)
  .filter((f) => /\.(svg|png|webp)$/i.test(f))
  .map((f) => {
    const ext = f.slice(f.lastIndexOf(".") + 1).toLowerCase();
    const kind = f.slice(0, f.lastIndexOf("."));
    return [kind, ext];
  })
  .filter(([kind]) => {
    if (!KNOWN_KINDS.includes(kind)) {
      console.warn(`Skipping public/tiles/${kind} — not a known TileKind`);
      return false;
    }
    return true;
  })
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([kind, ext]) => `  ${JSON.stringify(kind)}: ${JSON.stringify(ext)},`).join("\n");

const content = `// AUTO-GENERATED by scripts/generate-tile-manifest.mjs — do not edit by hand.
// Maps a TileKind to the file extension of its real artwork in public/tiles/.
import type { TileKind } from "@/lib/questions/types";

export const REAL_TILE_FILES: Partial<Record<TileKind, "svg" | "png" | "webp">> = {
${body}
};
`;

writeFileSync(outFile, content);
console.log(`Wrote ${entries.length} entries to ${path.relative(process.cwd(), outFile)}`);
