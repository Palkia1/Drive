// Scans public/scenes/*.svg for the "module-slots" marker layer each
// background carries (see any file in public/scenes/ for the convention:
// <circle data-slot="..." data-role="actor|sign" ...>, plus an optional
// single data-role="ring-geometry" marker for roundabout-style backgrounds)
// and writes src/lib/scenes/locationSlots.generated.ts — the coordinates a
// vehicle/sign may be placed at, read directly out of the artwork instead of
// a hand-typed table living apart from it. Re-run after moving a marker
// (npm run scenes:manifest).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const scenesDir = path.join(root, "..", "public", "scenes");
const outFile = path.join(root, "..", "src", "lib", "scenes", "locationSlots.generated.ts");

/** Pulls every attribute off one self-closing/opening SVG tag's attribute string. */
function parseAttrs(attrString) {
  const attrs = {};
  for (const m of attrString.matchAll(/([\w:-]+)="([^"]*)"/g)) attrs[m[1]] = m[2];
  return attrs;
}

function num(attrs, name, fallback) {
  const v = attrs[name];
  return v === undefined ? fallback : Number(v);
}

const locations = {};

for (const file of readdirSync(scenesDir)) {
  if (!file.endsWith(".svg")) continue;
  const locationId = file.slice(0, -4);
  const src = readFileSync(path.join(scenesDir, file), "utf8");
  const slotsMatch = src.match(/<g id="module-slots"[\s\S]*?<\/g>/);
  if (!slotsMatch) continue; // e.g. stoplicht-rood-losse-ringen.svg — a plain icon, not a slotted background

  const actorSlots = {};
  const signSlots = {};
  let ringGeometry = null;

  for (const tagMatch of slotsMatch[0].matchAll(/<circle\s+([^/>]+)\/?>/g)) {
    const a = parseAttrs(tagMatch[1]);
    if (a["data-role"] === "ring-geometry") {
      ringGeometry = {
        x: num(a, "cx", 0),
        y: num(a, "cy", 0),
        approachRadius: num(a, "data-approach-radius", 0),
        ringRadius: num(a, "data-ring-radius", 0),
        laneOffset: num(a, "data-lane-offset", 0),
        ringLeadDeg: num(a, "data-ring-lead-deg", 0),
      };
      continue;
    }
    const slot = a["data-slot"];
    if (!slot) continue;
    if (a["data-role"] === "actor") {
      actorSlots[slot] = {
        x: num(a, "cx", 0),
        y: num(a, "cy", 0),
        rotation: num(a, "data-rotation", 0),
        scale: num(a, "data-scale", 1),
        bearing: num(a, "data-bearing", 0),
      };
    } else if (a["data-role"] === "sign") {
      signSlots[slot] = { x: num(a, "cx", 0), y: num(a, "cy", 0) };
    }
  }

  locations[locationId] = { actorSlots, signSlots, ringGeometry };
}

const sortedIds = Object.keys(locations).sort();

function tsObject(obj, indent) {
  const pad = "  ".repeat(indent);
  const innerPad = "  ".repeat(indent + 1);
  const lines = Object.entries(obj).map(([k, v]) => `${innerPad}${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return `{\n${lines.join("\n")}\n${pad}}`;
}

const actorBody = sortedIds.map((id) => `  ${JSON.stringify(id)}: ${tsObject(locations[id].actorSlots, 1)},`).join("\n");
const signBody = sortedIds.map((id) => `  ${JSON.stringify(id)}: ${tsObject(locations[id].signSlots, 1)},`).join("\n");
const ringBody = sortedIds
  .filter((id) => locations[id].ringGeometry)
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(locations[id].ringGeometry)},`)
  .join("\n");

const content = `// AUTO-GENERATED by scripts/generate-scene-manifest.mjs — do not edit by hand.
// Source of truth: the "module-slots" marker layer inside each
// public/scenes/{locationId}.svg — move a marker there and re-run
// \`npm run scenes:manifest\` to pick it up here.

export type ActorSlot = { x: number; y: number; rotation: number; scale: number; bearing: number };
export type SignSlot = { x: number; y: number };
export type RingGeometry = { x: number; y: number; approachRadius: number; ringRadius: number; laneOffset: number; ringLeadDeg: number };

export const LOCATION_ACTOR_SLOTS: Record<string, Record<string, ActorSlot>> = {
${actorBody}
};

export const LOCATION_SIGN_SLOTS: Record<string, Record<string, SignSlot>> = {
${signBody}
};

export const LOCATION_RING_GEOMETRY: Record<string, RingGeometry> = {
${ringBody}
};
`;

writeFileSync(outFile, content);
console.log(`Wrote ${sortedIds.length} location(s) to ${path.relative(process.cwd(), outFile)}`);
