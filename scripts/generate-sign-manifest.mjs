// Scans public/signs/ and writes src/lib/questions/realSigns.generated.ts —
// a map of RVV code -> file extension, so SignIcon knows which signs have
// real artwork vs. need the hand-drawn fallback. Re-run this after adding
// or removing files in public/signs/ (npm run signs:manifest).
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(import.meta.url));
const signsDir = path.join(root, "..", "public", "signs");
const outFile = path.join(root, "..", "src", "lib", "questions", "realSigns.generated.ts");

const entries = readdirSync(signsDir)
  .filter((f) => /\.(svg|png)$/i.test(f))
  .map((f) => {
    const ext = f.slice(f.lastIndexOf(".") + 1).toLowerCase();
    const code = f.slice(0, f.lastIndexOf("."));
    return [code, ext];
  })
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([code, ext]) => `  ${JSON.stringify(code)}: ${JSON.stringify(ext)},`).join("\n");

const content = `// AUTO-GENERATED by scripts/generate-sign-manifest.mjs — do not edit by hand.
// Maps an RVV code to the file extension of its real artwork in public/signs/.
export const REAL_SIGN_FILES: Record<string, "svg" | "png"> = {
${body}
};
`;

writeFileSync(outFile, content);
console.log(`Wrote ${entries.length} entries to ${path.relative(process.cwd(), outFile)}`);
