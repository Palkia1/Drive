// Generates the 8 GridScene tile SVGs with exact, mathematically-consistent
// geometry (road width, colors, dash phase) — no AI image-gen guesswork, so
// every tile is guaranteed to line up with its neighbors at the seams.
// Run: node scripts/generate-tile-art.mjs (or npm run tiles:generate).
// Writes to public/tiles/*.svg — re-run after changing any constant below,
// then `npm run tiles:manifest` to refresh the kind->extension map.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../public/tiles");
fs.mkdirSync(outDir, { recursive: true });

const SIZE = 1024;
const C = 512; // tile center
const ROAD = 312;
const HALF_ROAD = ROAD / 2; // 156
const NARROW = 200;

const ASPHALT = "#596168";
const GRASS = "#9FC77D";
const MARK = "#F7F5ED";

// Dash period (40 on + 24 off = 64) divides 1024 evenly (16x), so a
// full-length dash line starts AND ends exactly on a dash — no phase
// mismatch at either tile edge.
const DASH = `stroke="${MARK}" stroke-width="10" stroke-dasharray="40 24" stroke-linecap="butt"`;

function grassBg() {
  // Flat fill plus a handful of deterministic subtle darker patches for a
  // touch of texture without complexity.
  const patches = [];
  let seed = 7;
  const rand = () => {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  };
  for (let i = 0; i < 24; i++) {
    const x = rand() * SIZE;
    const y = rand() * SIZE;
    const r = 14 + rand() * 22;
    patches.push(`<ellipse cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" rx="${r.toFixed(1)}" ry="${(r * 0.6).toFixed(1)}" fill="#8FBB6E" opacity="0.35" />`);
  }
  return `<rect width="${SIZE}" height="${SIZE}" fill="${GRASS}" />\n${patches.join("\n")}`;
}

function wrap(name, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">
  <!-- ${name} — generated by scripts/gen-placeholder-tiles.mjs, canonical rotation 0 -->
${body}
</svg>
`;
}

function write(name, svg) {
  fs.writeFileSync(path.join(outDir, `${name}.svg`), svg);
  console.log("wrote", name + ".svg");
}

// ---- grass ------------------------------------------------------------
write("grass", wrap("grass", `  ${grassBg()}`));

// ---- straight (vertical, full height) ----------------------------------
function straightSvg(width, name) {
  const half = width / 2;
  return wrap(name, `  ${grassBg()}
  <rect x="${C - half}" y="0" width="${width}" height="${SIZE}" fill="${ASPHALT}" />
  <line x1="${C}" y1="0" x2="${C}" y2="${SIZE}" ${DASH} />`);
}
write("straight", straightSvg(ROAD, "straight"));
write("narrow-residential", straightSvg(NARROW, "narrow-residential"));

// ---- t-junction (stem north; through-road east-west; south closed) -----
write(
  "t-junction",
  wrap(
    "t-junction",
    `  ${grassBg()}
  <rect x="0" y="${C - HALF_ROAD}" width="${SIZE}" height="${ROAD}" fill="${ASPHALT}" />
  <rect x="${C - HALF_ROAD}" y="0" width="${ROAD}" height="${C + HALF_ROAD}" fill="${ASPHALT}" />
  <line x1="0" y1="${C}" x2="${SIZE}" y2="${C}" ${DASH} />
  <line x1="${C}" y1="0" x2="${C}" y2="${C - HALF_ROAD}" ${DASH} />`
  )
);

// ---- crossroad ----------------------------------------------------------
write(
  "crossroad",
  wrap(
    "crossroad",
    `  ${grassBg()}
  <rect x="${C - HALF_ROAD}" y="0" width="${ROAD}" height="${SIZE}" fill="${ASPHALT}" />
  <rect x="0" y="${C - HALF_ROAD}" width="${SIZE}" height="${ROAD}" fill="${ASPHALT}" />
  <line x1="${C}" y1="0" x2="${C}" y2="${SIZE}" ${DASH} />
  <line x1="0" y1="${C}" x2="${SIZE}" y2="${C}" ${DASH} />`
  )
);

// ---- corner / wide-curve (south -> east bend) ---------------------------
// Centerline bend of radius R around arc-center Cp = (C+R, C+R): a quarter
// circle from the south-arm centerline (tangent at (C, C+R)) to the east-arm
// centerline (tangent at (C+R, C)). Outer road edge = R+HALF_ROAD, inner =
// R-HALF_ROAD (must stay positive, i.e. R > HALF_ROAD).
function bendSvg(name, R) {
  const Cp = C + R;
  const outer = R + HALF_ROAD;
  const inner = R - HALF_ROAD;
  const fill = `
    M ${C - HALF_ROAD},${SIZE}
    L ${C - HALF_ROAD},${Cp}
    A ${outer},${outer} 0 0 1 ${Cp},${C - HALF_ROAD}
    L ${SIZE},${C - HALF_ROAD}
    L ${SIZE},${C + HALF_ROAD}
    L ${Cp},${C + HALF_ROAD}
    A ${inner},${inner} 0 0 0 ${C + HALF_ROAD},${Cp}
    L ${C + HALF_ROAD},${SIZE}
    Z
  `.trim();
  const centerline = `M ${C},${SIZE} L ${C},${Cp} A ${R},${R} 0 0 1 ${Cp},${C} L ${SIZE},${C}`;
  return wrap(
    name,
    `  ${grassBg()}
  <path d="${fill}" fill="${ASPHALT}" />
  <path d="${centerline}" fill="none" ${DASH} />`
  );
}
write("corner", bendSvg("corner", 260));
write("wide-curve", bendSvg("wide-curve", 400));

// ---- roundabout-center ---------------------------------------------------
const RING_OUTER = 320;
const RING_WIDTH = 200;
const ISLAND = RING_OUTER - RING_WIDTH; // 120
const DASH_ARM_END = C - RING_OUTER; // dashes stop short of the ring
write(
  "roundabout-center",
  wrap(
    "roundabout-center",
    `  ${grassBg()}
  <circle cx="${C}" cy="${C}" r="${RING_OUTER}" fill="${ASPHALT}" />
  <rect x="${C - HALF_ROAD}" y="0" width="${ROAD}" height="${C}" fill="${ASPHALT}" />
  <rect x="${C - HALF_ROAD}" y="${C}" width="${ROAD}" height="${C}" fill="${ASPHALT}" />
  <rect x="0" y="${C - HALF_ROAD}" width="${C}" height="${ROAD}" fill="${ASPHALT}" />
  <rect x="${C}" y="${C - HALF_ROAD}" width="${C}" height="${ROAD}" fill="${ASPHALT}" />
  <circle cx="${C}" cy="${C}" r="${ISLAND}" fill="${GRASS}" />
  <line x1="${C}" y1="0" x2="${C}" y2="${DASH_ARM_END}" ${DASH} />
  <line x1="${C}" y1="${SIZE - DASH_ARM_END}" x2="${C}" y2="${SIZE}" ${DASH} />
  <line x1="0" y1="${C}" x2="${DASH_ARM_END}" y2="${C}" ${DASH} />
  <line x1="${SIZE - DASH_ARM_END}" y1="${C}" x2="${SIZE}" y2="${C}" ${DASH} />`
  )
);

console.log("Done.");
